@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PythonHubScreen(
    onBack: () -> Unit,
    onSyntax: () -> Unit,
    onFunctions: () -> Unit,
    onVariables: () -> Unit,
    onClassesObjects: () -> Unit
) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text       = "Python",
                        color      = Color(0xFF00FF41),
                        fontFamily = FontFamily.Monospace,
                        fontSize   = 16.sp
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            imageVector        = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = "Back",
                            tint               = Color.White
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = Color.Black)
            )
        },
        containerColor = Color.Black
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .padding(horizontal = 32.dp)
                .verticalScroll(rememberScrollState()),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Spacer(Modifier.height(24.dp))
            HubButton("Syntax",             onSyntax)
            Spacer(Modifier.height(12.dp))
            HubButton("Variables",          onVariables)
            Spacer(Modifier.height(12.dp))
            HubButton("Functions",          onFunctions)
            Spacer(Modifier.height(12.dp))
            HubButton("Classes & Objects",  onClassesObjects)
            Spacer(Modifier.height(24.dp))
        }
    }
}

@Composable
private fun HubButton(label: String, onClick: () -> Unit) {
    OutlinedButton(
        onClick  = onClick,
        modifier = Modifier
            .fillMaxWidth()
            .height(52.dp),
        border = BorderStroke(1.dp, Color(0xFF00FF41)),
        colors = ButtonDefaults.outlinedButtonColors(
            containerColor = Color.Black,
            contentColor   = Color(0xFF00FF41)
        )
    ) {
        Text(
            text       = label,
            fontFamily = FontFamily.Monospace,
            fontWeight = FontWeight.Medium,
            color      = Color(0xFF00FF41),
            textAlign  = TextAlign.Center
        )
    }
}
