        PrepBodyText("من مين (min miin) — from whom")
        PrepBodyText("مين (miin) — who / whom")
        PrepBodyText("جوا (jawwa) — inside")
        PrepBodyText("برا (barra) — outside")
        PrepBodyText("فوق (foo2) / على (3ala) — on / above")
