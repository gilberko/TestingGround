        Spacer(modifier = Modifier.height(8.dp))
        PrepBodyText("HOPING FOR — متمني على (mitmanni 3ala) / عم بتمنى إنو (3am batmanna inno)")
        PrepBodyText("• عم بتمنى إنو يصير هيك — 3am batmanna inno yisir hayk — I'm hoping for this to happen")
        PrepBodyText("• متمني على خبر منك — mitmanni 3ala khabar minnak — hoping to hear from you")
        PrepBodyText("• بتمنى يزبط الموضوع — batmanna yizbut il-mawdu3 — hoping for things to work out")

        PrepSectionHeader("Quick Reference")
        PrepBodyText("و (w) — and")
        PrepBodyText("أو (aw) / ولا (wella) — or")
        PrepBodyText("مش (mish) — not (non-verb)")
        PrepBodyText("ما...ش (ma...sh) — not (verb negation)")
        PrepBodyText("بلا (bala) / بدون (bidun) — without")
        PrepBodyText("لهيك (la-hek) — therefore")
        PrepBodyText("مع إنو (ma3 inno) — even though")
